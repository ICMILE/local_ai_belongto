def extract_cookies(browser: str, domain: str):
    import rookie_cookies
    func = getattr(rookie_cookies, browser)
    print(f"[*] extract_cookies: browser={browser}, domain={domain}")
    cookies = func([domain])
    print(f"[*] success capture {len(cookies)} cookies")
    return cookies

def _get(c, key, default=None):
    """兼容 dict 与对象两种返回格式"""
    if isinstance(c, dict):
        return c.get(key, default)
    return getattr(c, key, default)


def save_netscape(cookies, path: str):
    """把 cookies 写成 Netscape 格式 (cookies.txt)"""
    lines = [
        "# Netscape HTTP Cookie File",
        "# This file was generated by rookie-cookies",
        "",
    ]
    for c in cookies:
        name    = _get(c, "name", "") or ""
        value   = _get(c, "value", "") or ""
        domain  = _get(c, "domain", "") or ""
        cpath   = _get(c, "path", "/") or "/"
        secure  = _get(c, "secure", False)
        expires = _get(c, "expires", 0) or _get(c, "expiration", 0) or 0

        domain_flag = "TRUE" if domain.startswith(".") else "FALSE"
        secure_str  = "TRUE" if secure else "FALSE"
        try:
            expires = int(expires)
        except (TypeError, ValueError):
            expires = 0

        lines.append(
            f"{domain}\t{domain_flag}\t{cpath}\t{secure_str}\t{expires}\t{name}\t{value}"
        )

    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))
    print(f"[*] Cookies 已写入临时文件: {path}")


def download(url: str, cookie_file: str, output_dir: str):
    os.makedirs(output_dir, exist_ok=True)
    ydl_opts = {
        "cookiefile": cookie_file,
        "format": FORMAT,
        "merge_output_format": "mp4",
        "outtmpl": os.path.join(output_dir, "%(title)s.%(ext)s"),
        "retries": 5,
        "fragment_retries": 5,
        "noprogress": False,
        "remote_components": ["ejs:github"], 
    }
    with YoutubeDL(ydl_opts) as ydl:
        ydl.download([url])


def main():
    tmp_fd, tmp_path = tempfile.mkstemp(prefix="yt_cookies_", suffix=".txt")
    os.close(tmp_fd)

    try:
        cookies = extract_cookies(BROWSER, COOKIE_DOMAIN)
        save_netscape(cookies, tmp_path)
        print("[*] 开始下载 ...")
        download(VIDEO_URL, tmp_path, OUTPUT_DIR)
        print(f"[✓] 下载完成，文件保存在: {OUTPUT_DIR}")
    finally:
        if os.path.exists(tmp_path):
            os.remove(tmp_path)
            print("[*] 已清理临时 cookies 文件")


if __name__ == "__main__":
    main()
